export function resourceExplanation(name, kind = 'skill') {
  const n = String(name || '').toLowerCase();
  if (n.includes('cosmos'))
    return 'בדיקה ייעודית לבלוקצ׳יין Cosmos: חיפוש קלט שיכול להפיל עיבוד בלוקים. אינה מיועדת לאתר רגיל. מקור: תהליך מובנה של Open-Kritt.';
  if (n.includes('external-flow'))
    return 'ממפה כניסות חיצוניות ועוקב אחר המידע בקוד כדי לחפש חולשות. מתאים לשרתים ול־API. מקור: תהליך מובנה של Open-Kritt.';
  if (n.includes('אוטומטית'))
    return 'מסלול שהוספנו להתאמה זו: מזהה את הפרויקט, מתכנן תחומי בדיקה ומאמת ממצאים. בגרסה 2 משולב גם כלי מקומי ודוח כיסוי. אינו מבטיח למצוא כל חולשה.';
  const base =
    kind === 'workflow'
      ? 'תוכנית עבודה של סוכן AI. קראו את המטרה והשלבים לפני הבחירה.'
      : 'מיומנות היא הוראות לסוכן AI; אינה בהכרח תוכנה מותקנת או כלי שרץ אוטומטית. בפריטים המקוריים חלק מהתוכן הוא תקציר וקישור למקור, ולא המיומנות המקורית המלאה.';
  const topics = [
    [/solidity|solana|pashov/, 'מיועד בעיקר לחוזים חכמים ובלוקצ׳יין.'],
    [/fuzz|libfuzzer/, 'בדיקות עם הרבה קלטים משתנים; דורשות כלי הרצה ותשתית מתאימים.'],
    [/supply|תלויות/, 'בודק סיכונים בספריות, בנייה ופרסום חבילות.'],
    [/constant.time|zeroize|הצפנה/, 'מתמקד בטיפול בסודות ובהצפנה.'],
    [/semgrep|static|codeql/, 'מנחה שימוש בניתוח סטטי. בחירה בו אינה מתקינה או מפעילה Semgrep/CodeQL כשלעצמה.'],
    [/false.positive|אימות/, 'מסייע לבדוק אם ממצא הוא בעיה אמיתית או התרעת שווא.'],
    [/entry.point/, 'ממפה מקומות שבהם קלט חיצוני נכנס לקוד.'],
    [/variant/, 'מחפש מופעים נוספים של בעיה שכבר זוהתה.'],
    [/yara/, 'מיועד לכתיבת כללי זיהוי תוכנות זדוניות; אינו סריקת אבטחה כללית של אתר.'],
    [/burp/, 'מיועד לניתוח תעבורת HTTP ונתוני Burp קיימים.'],
    [/auth|הרשאות/, 'מתמקד בכניסה, הרשאות ובעלות על מידע.'],
  ];
  return (
    base +
    ' ' +
    (topics.find(([pattern]) => pattern.test(n))?.[1] || 'השתמשו רק אם התיאור מתאים לטכנולוגיה ולמטרה שלכם.')
  );
}
