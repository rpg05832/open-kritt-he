function words(value) {
  if (typeof value === 'string' || typeof value === 'number') return String(value);
  if (Array.isArray(value)) return value.map(words).join(' ');
  return value?.props ? words(value.props.children) : '';
}
export default function HelpTip({ term, description }) {
  const [open, setOpen] = useState(false);
  const id = useId();
  const label = words(term).trim();
  const entry = explanations.find(([pattern]) => new RegExp(pattern, 'i').test(label));
  if (!entry && !description) return null;
  return (
    <span className="help-tip">
      <button
        type="button"
        aria-label={'הסבר: ' + label}
        aria-expanded={open}
        aria-describedby={open ? id : undefined}
        onClick={(e) => {
          e.preventDefault();
          e.stopPropagation();
          setOpen(true);
        }}
        onKeyDown={(e) => {
          if (e.key === 'Escape') setOpen(false);
        }}
        onMouseEnter={() => setOpen(true)}
        onMouseLeave={() => setOpen(false)}
        onFocus={() => setOpen(true)}
        onBlur={() => setOpen(false)}
      >
        ?
      </button>
      {open && (
        <span id={id} role="tooltip" className="help-tip-panel" dir="rtl">
          {description || entry[1]}
        </span>
      )}
    </span>
  );
}
